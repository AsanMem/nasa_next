import { lstatSync, readFileSync, realpathSync, unlinkSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const RUNTIME_ENV_FILENAME = ".env.nasa-odisey";
const GENERATED_HEADER = "# Generated by Orbital CI runtime preparation. Do not commit.\n";

class RuntimeConfigurationError extends Error {}

function assertProjectRoot(root) {
  try {
    const resolved = realpathSync(root);
    const packageJson = JSON.parse(readFileSync(join(resolved, "package.json"), "utf8"));
    const firebase = JSON.parse(readFileSync(join(resolved, "firebase.json"), "utf8"));
    const projects = JSON.parse(readFileSync(join(resolved, ".firebaserc"), "utf8"));
    if (packageJson.name !== "nasa_next" || firebase.hosting?.source !== "." || projects.projects?.default !== "nasa-odisey") {
      throw new Error();
    }
    return resolved;
  } catch {
    throw new RuntimeConfigurationError("Run this helper from the nasa-odisey application root.");
  }
}

function nasaKey(env) {
  const raw = env.NASA_API_KEY;
  if (typeof raw !== "string" || !raw.trim()) {
    throw new RuntimeConfigurationError("NASA_API_KEY is required for Firebase SSR deployment.");
  }
  if (/[\u0000-\u001f\u007f-\u009f]/.test(raw)) {
    throw new RuntimeConfigurationError("NASA_API_KEY has an invalid format.");
  }
  const value = raw.trim();
  if (value.toUpperCase() === "DEMO_KEY") {
    throw new RuntimeConfigurationError("Firebase SSR deployment requires a configured NASA_API_KEY, not DEMO_KEY.");
  }
  if (!/^[A-Za-z0-9_-]{1,256}$/.test(value)) {
    throw new RuntimeConfigurationError("NASA_API_KEY has an invalid format.");
  }
  return value;
}

export function prepareFirebaseRuntimeEnv({ root = process.cwd(), env = process.env } = {}) {
  const projectRoot = assertProjectRoot(root);
  const value = nasaKey(env);
  const destination = join(projectRoot, RUNTIME_ENV_FILENAME);
  try {
    // Exclusive creation protects any existing local credentials. Firebase's
    // framework adapter copies this project-scoped dotenv into the SSR backend;
    // its Functions env loader reads .env.<projectId> at deployment time.
    writeFileSync(destination, `${GENERATED_HEADER}NASA_API_KEY=${value}\n`, { flag: "wx", mode: 0o600 });
  } catch (error) {
    if (error?.code === "EEXIST") {
      throw new RuntimeConfigurationError(`Refusing to overwrite an existing ${RUNTIME_ENV_FILENAME}.`);
    }
    throw new RuntimeConfigurationError("Unable to write the Firebase SSR runtime configuration.");
  }
  return destination;
}

export function cleanupFirebaseRuntimeEnv({ root = process.cwd() } = {}) {
  const projectRoot = assertProjectRoot(root);
  const destination = join(projectRoot, RUNTIME_ENV_FILENAME);
  let stats;
  try {
    stats = lstatSync(destination);
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw new RuntimeConfigurationError("Unable to inspect the Firebase SSR runtime configuration.");
  }
  if (!stats.isFile() || stats.isSymbolicLink()) {
    throw new RuntimeConfigurationError("Refusing to remove an unmanaged Firebase runtime configuration.");
  }
  try {
    if (!readFileSync(destination, "utf8").startsWith(GENERATED_HEADER)) {
      throw new RuntimeConfigurationError("Refusing to remove an unmanaged Firebase runtime configuration.");
    }
    unlinkSync(destination);
    return true;
  } catch (error) {
    if (error instanceof RuntimeConfigurationError) throw error;
    throw new RuntimeConfigurationError("Unable to remove the generated Firebase SSR runtime configuration.");
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (!args.length) {
      prepareFirebaseRuntimeEnv();
      console.log("Prepared server-only NASA configuration for the Firebase SSR backend.");
    } else if (args.length === 1 && args[0] === "--cleanup") {
      cleanupFirebaseRuntimeEnv();
      console.log("Firebase SSR temporary configuration cleanup complete.");
    } else {
      throw new RuntimeConfigurationError("Usage: node scripts/prepare-firebase-env.mjs [--cleanup]");
    }
  } catch (error) {
    console.error(error instanceof RuntimeConfigurationError ? error.message : "Firebase SSR runtime configuration failed.");
    process.exitCode = 1;
  }
}
