const assert = require('node:assert/strict');
const { mkdtempSync, readFileSync, rmSync, statSync, writeFileSync, existsSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join, resolve } = require('node:path');
const { spawnSync } = require('node:child_process');
const { pathToFileURL } = require('node:url');
const test = require('node:test');

const repo = resolve(__dirname, '..');
const helper = join(repo, 'scripts', 'prepare-firebase-env.mjs');
const modulePromise = import(pathToFileURL(helper).href);

function project(t) {
  const root = mkdtempSync(join(tmpdir(), 'orbital-runtime-env-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  writeFileSync(join(root, 'package.json'), JSON.stringify({ name: 'nasa_next' }));
  writeFileSync(join(root, 'firebase.json'), JSON.stringify({ hosting: { source: '.' } }));
  writeFileSync(join(root, '.firebaserc'), JSON.stringify({ projects: { default: 'nasa-odisey' } }));
  return root;
}

test('writes only the server NASA key to Firebase project-scoped dotenv', async (t) => {
  const api = await modulePromise;
  const root = project(t);
  const file = api.prepareFirebaseRuntimeEnv({ root, env: { NASA_API_KEY: 'runtime-test-key', UNRELATED_SECRET: 'must-not-copy', NEXT_PUBLIC_FIREBASE_API_KEY: 'public-test-value' } });
  assert.equal(file, join(root, '.env.nasa-odisey'));
  const content = readFileSync(file, 'utf8');
  assert.match(content, /^# Generated by Orbital CI runtime preparation\./);
  assert.equal(content.split('\n').filter((line) => line && !line.startsWith('#')).join('\n'), 'NASA_API_KEY=runtime-test-key');
  assert.ok(!content.includes('must-not-copy'));
  assert.ok(!content.includes('NEXT_PUBLIC_'));
  if (process.platform !== 'win32') assert.equal(statSync(file).mode & 0o777, 0o600);
  assert.equal(api.cleanupFirebaseRuntimeEnv({ root }), true);
  assert.equal(existsSync(file), false);
  assert.equal(api.cleanupFirebaseRuntimeEnv({ root }), false);
});

test('missing, shared demo and multiline/control-bearing keys fail before creating a file', async (t) => {
  const api = await modulePromise;
  const root = project(t);
  for (const value of [undefined, '', '  ', 'DEMO_KEY', 'demo_key', 'LEAK_TEST\nOTHER=value', 'LEAK_TEST\r', 'LEAK_TEST\0', 'LEAK_TEST\t', 'LEAK_TEST\u007f', 'LEAK_TEST"', 'LEAK_TEST$value']) {
    assert.throws(() => api.prepareFirebaseRuntimeEnv({ root, env: { NASA_API_KEY: value } }), (error) => {
      assert.ok(!error.message.includes('LEAK_TEST'));
      return true;
    });
    assert.equal(existsSync(join(root, api.RUNTIME_ENV_FILENAME)), false);
  }
});

test('existing credentials survive both prepare failure and unconditional cleanup', async (t) => {
  const api = await modulePromise;
  const root = project(t);
  const file = join(root, api.RUNTIME_ENV_FILENAME);
  const original = 'NASA_API_KEY=existing-local-value\nOTHER=preserve\n';
  writeFileSync(file, original);
  assert.throws(() => api.prepareFirebaseRuntimeEnv({ root, env: { NASA_API_KEY: 'replacement-test-key' } }), /Refusing to overwrite/);
  assert.throws(() => api.cleanupFirebaseRuntimeEnv({ root }), /unmanaged/);
  assert.equal(readFileSync(file, 'utf8'), original);
});

test('refuses another Firebase project and CLI never accepts an arbitrary root argument', async (t) => {
  const api = await modulePromise;
  const root = project(t);
  writeFileSync(join(root, '.firebaserc'), JSON.stringify({ projects: { default: 'another-project' } }));
  assert.throws(() => api.prepareFirebaseRuntimeEnv({ root, env: { NASA_API_KEY: 'runtime-test-key' } }), /application root/);
  const result = spawnSync(process.execPath, [helper, '--root', root], { cwd: root, env: { ...process.env, NASA_API_KEY: 'LEAK_TEST_KEY' }, encoding: 'utf8' });
  assert.equal(result.status, 1);
  assert.ok(!`${result.stdout}${result.stderr}`.includes('LEAK_TEST_KEY'));
});

test('CLI output is secret-free on success, failure and cleanup', (t) => {
  const root = project(t);
  const env = { ...process.env, NASA_API_KEY: 'LEAK_TEST_KEY' };
  const prepared = spawnSync(process.execPath, [helper], { cwd: root, env, encoding: 'utf8' });
  assert.equal(prepared.status, 0);
  const rejected = spawnSync(process.execPath, [helper], { cwd: root, env, encoding: 'utf8' });
  assert.equal(rejected.status, 1);
  const cleaned = spawnSync(process.execPath, [helper, '--cleanup'], { cwd: root, env, encoding: 'utf8' });
  assert.equal(cleaned.status, 0);
  for (const result of [prepared, rejected, cleaned]) {
    assert.ok(!`${result.stdout}${result.stderr}`.includes('LEAK_TEST_KEY'));
  }
});

test('both workflows prepare runtime env before deployment and clean it on every outcome', () => {
  for (const name of ['firebase-hosting-merge.yml', 'firebase-hosting-pull-request.yml']) {
    const workflow = readFileSync(join(repo, '.github', 'workflows', name), 'utf8');
    const prepare = workflow.indexOf('run: node scripts/prepare-firebase-env.mjs\n');
    const deploy = workflow.indexOf('uses: FirebaseExtended/action-hosting-deploy@v0');
    const cleanup = workflow.indexOf('run: node scripts/prepare-firebase-env.mjs --cleanup');
    assert.ok(prepare >= 0 && prepare < deploy && deploy < cleanup);
    assert.match(workflow.slice(deploy, cleanup), /if: \$\{\{ always\(\) \}\}/);
    assert.match(workflow, /NASA_API_KEY: \$\{\{ secrets\.NASA_API_KEY \}\}/);
    assert.ok(!workflow.includes('NEXT_PUBLIC_NASA_API_KEY'));
  }
  const merge = readFileSync(join(repo, '.github', 'workflows', 'firebase-hosting-merge.yml'), 'utf8');
  const preview = readFileSync(join(repo, '.github', 'workflows', 'firebase-hosting-pull-request.yml'), 'utf8');
  assert.match(merge, /channelId: live/);
  assert.match(merge, /cron: "17 6,18 \* \* \*"/);
  assert.ok(!preview.includes('channelId: live'));
  assert.match(preview, /DEPLOYMENT_URL: \$\{\{ steps\.firebase_deploy\.outputs\.details_url \}\}/);
  assert.match(preview, /node scripts\/smoke-deployment\.mjs "\$DEPLOYMENT_URL"/);
  assert.match(preview, /head\.repo\.full_name == github\.repository/);
  assert.ok(readFileSync(join(repo, '.gitignore'), 'utf8').split(/\r?\n/).includes('.env.nasa-odisey'));
});
